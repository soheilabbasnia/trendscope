import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';

async function bundleDashboard() {
  console.log('[Build] Bundling React Dashboard with esbuild...');

  const result = await build({
    entryPoints: ['src/dashboard/main.tsx'],
    bundle: true,
    minify: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: ['es2020'],
    define: {
      'process.env.NODE_ENV': '"production"',
    },
  });

  const bundledJs = result.outputFiles[0].text;
  console.log(`[Build] Bundle size: ${(bundledJs.length / 1024).toFixed(1)} KB`);

  const htmlContent = `<!DOCTYPE html>
<html lang="fa" dir="rtl">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>TrendScope | سامانه هوشمند پایش و پالایش اخبار فناوری</title>
  <script src="https://cdn.tailwindcss.com"></script>
  <script>
    tailwind.config = {
      theme: {
        extend: {
          fontFamily: {
            sans: ['Ravi', '-apple-system', 'BlinkMacSystemFont', 'sans-serif'],
            heading: ['Anjoman', 'Ravi', 'sans-serif'],
          }
        }
      }
    };
  </script>
  <style>
    @font-face {
      font-family: 'Anjoman';
      src: url('/api/fonts/Anjoman-Bold.woff2') format('woff2');
      font-weight: 700;
      font-style: normal;
      font-display: swap;
    }
    @font-face {
      font-family: 'Anjoman';
      src: url('/api/fonts/Anjoman-SemiBold.woff2') format('woff2');
      font-weight: 600;
      font-style: normal;
      font-display: swap;
    }
    @font-face {
      font-family: 'Ravi';
      src: url('/api/fonts/Ravi-Regular.woff2') format('woff2');
      font-weight: 400;
      font-style: normal;
      font-display: swap;
    }
    @font-face {
      font-family: 'Ravi';
      src: url('/api/fonts/Ravi-Medium.woff2') format('woff2');
      font-weight: 500;
      font-style: normal;
      font-display: swap;
    }
    @font-face {
      font-family: 'Ravi';
      src: url('/api/fonts/Ravi-Bold.woff2') format('woff2');
      font-weight: 700;
      font-style: normal;
      font-display: swap;
    }

    body, html {
      margin: 0;
      padding: 0;
      font-family: 'Ravi', -apple-system, BlinkMacSystemFont, sans-serif;
      background-color: #080808;
      color: #F5F1E8;
      -webkit-font-smoothing: antialiased;
    }

    h1, h2, h3, h4, h5, h6, .font-heading {
      font-family: 'Anjoman', 'Ravi', sans-serif !important;
    }

    .scrollbar-thin::-webkit-scrollbar {
      width: 6px;
      height: 6px;
    }
    .scrollbar-thin::-webkit-scrollbar-track {
      background: #080808;
    }
    .scrollbar-thin::-webkit-scrollbar-thumb {
      background: rgba(212, 175, 55, 0.2);
      border-radius: 3px;
    }
    .scrollbar-thin::-webkit-scrollbar-thumb:hover {
      background: rgba(212, 175, 55, 0.4);
    }
  </style>
</head>
<body class="bg-[#080808] text-[#F5F1E8] min-h-screen font-sans">
  <div id="root"></div>
  <script>
${bundledJs.replace(/<\/script>/gi, '<\\/script>')}
  </script>
</body>
</html>`;

  const tsModule = `// Auto-generated by scripts/build-dashboard.js
export const DASHBOARD_HTML = ${JSON.stringify(htmlContent)};
`;

  fs.writeFileSync(path.resolve('src/dashboard/bundledHtml.ts'), tsModule, 'utf8');
  console.log('[Build] Successfully generated src/dashboard/bundledHtml.ts');
}

bundleDashboard().catch((err) => {
  console.error('[Build Error]', err);
  process.exit(1);
});
